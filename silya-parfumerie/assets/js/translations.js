// Translation Manager
class TranslationManager {
    constructor() {
        this.currentLang = localStorage.getItem('preferred-language') || 'fr';
        this.init();
    }

    init() {
        this.setLanguage(this.currentLang);
        this.attachEventListeners();
    }

    setLanguage(lang) {
        if (!translations[lang]) {
            console.error(`Language ${lang} not found`);
            return;
        }

        this.currentLang = lang;
        localStorage.setItem('preferred-language', lang);

        // Update HTML lang attribute
        document.documentElement.lang = lang;

        // Update RTL/LTR direction for Arabic
        if (lang === 'ar') {
            document.documentElement.dir = 'rtl';
            document.body.classList.add('rtl');
        } else {
            document.documentElement.dir = 'ltr';
            document.body.classList.remove('rtl');
        }

        // Update all translated elements
        this.updateTranslations();

        // Update active language button
        this.updateLanguageButtons();
    }

    updateTranslations() {
        const elements = document.querySelectorAll('[data-translate]');
        elements.forEach(element => {
            const key = element.getAttribute('data-translate');
            if (translations[this.currentLang][key]) {
                element.textContent = translations[this.currentLang][key];
            }
        });

        // Update placeholders
        const placeholderElements = document.querySelectorAll('[data-translate-placeholder]');
        placeholderElements.forEach(element => {
            const key = element.getAttribute('data-translate-placeholder');
            if (translations[this.currentLang][key]) {
                element.placeholder = translations[this.currentLang][key];
            }
        });
    }

    updateLanguageButtons() {
        const buttons = document.querySelectorAll('.lang-btn');
        buttons.forEach(btn => {
            const lang = btn.getAttribute('data-lang');
            if (lang === this.currentLang) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        });
    }

    attachEventListeners() {
        const langButtons = document.querySelectorAll('.lang-btn');
        langButtons.forEach(btn => {
            btn.addEventListener('click', () => {
                const lang = btn.getAttribute('data-lang');
                this.setLanguage(lang);
            });
        });
    }

    translate(key) {
        try {
            if (this.currentLang && translations[this.currentLang]) {
                return translations[this.currentLang][key] || key;
            }
            return key;
        } catch (error) {
            console.warn('Translation error:', error);
            return key;
        }
    }

    getCurrentLanguage() {
        return this.currentLang;
    }
}

// Helper function for safe translation (can be used before translationManager is initialized)
function safeTranslate(key, fallback) {
    try {
        if (typeof translationManager !== 'undefined' && translationManager) {
            return translationManager.translate(key);
        }
        return fallback || key;
    } catch (error) {
        return fallback || key;
    }
}

// Initialize translation manager when DOM is ready
let translationManager;
document.addEventListener('DOMContentLoaded', () => {
    translationManager = new TranslationManager();
});

// Export for use in other scripts
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { translations, TranslationManager };
}
